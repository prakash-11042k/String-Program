class Index_of_element_in_a_String 
{
	public static void main(String[] args) 
	{
		String s="ABCDEF";
		
		System.out.println(s.indexOf('A'));
		System.out.println(s.indexOf('D'));
		System.out.println(s.indexOf('A'));
		System.out.println(s.indexOf('Z'));
		System.out.println(s.indexOf('R'));
	}
}
